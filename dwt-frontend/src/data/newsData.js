// Helper pour calculer le temps de lecture estimé
export const calculateReadTime = (content) => {
  if (!content) return '3 min';
  const words = content.trim().split(/\s+/).length;
  const minutes = Math.max(1, Math.ceil(words / 180));
  return `${minutes} min`;
};